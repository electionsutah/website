// Exercise real repository records through Decap's official local filesystem backend.
// All writes are confined to a temporary workspace; repository content is never edited.
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { createServer } from 'vite';
import { prepare, syncRecord, validateRecord, atomicJson, readJson, root, overridesPath } from './workspace.mjs';
import { inspectSchema, saveSchema } from './schema.mjs';
import { elutThemeCss } from './elut-theme.mjs';

const require = createRequire(import.meta.url);
const { runDevServer } = require('@decap/cli/dev');
const directory = await mkdtemp(join(tmpdir(), 'elections-editor-'));
const baseline = await readFile(overridesPath, 'utf8');
const server = await createServer({ root, configFile: false, logLevel: 'silent', server: { middlewareMode: true, hmr: false, ws: false } });
let proxy;
try {
  const theme = await elutThemeCss();
  assert(theme.includes('--decap-active:var(--color-blue)'));
  assert(theme.includes("--font-sans:'Noto Sans'"));
  assert(theme.includes('--color-blue:#006eb7'));
  assert(theme.includes('/fonts/source-serif-4-normal-latin.woff2'));
  assert(theme.includes('--decap-font-primary:'));
  assert(!theme.includes('Georgia'));
  const saved = { version: 1, people: {}, filings: {} };
  const destination = join(directory, 'overrides.json');
  await atomicJson(destination, saved);
  const state = await prepare(server, directory, saved);
  const testSchemaPath = join(directory, 'schema.json');
  await atomicJson(testSchemaPath, { version: 1, collections: {} });
  let inspection = await inspectSchema(server, state, testSchemaPath);
  const filingSchema = inspection.collections.find(row => row.kind === 'filings');
  const reordered = filingSchema.fields.map(field => ({ path: field.path, label: field.label, ...(field.options ? { options: [...field.options] } : {}) })).reverse();
  reordered.find(field => field.path === 'status').label = 'Filing status';
  reordered.find(field => field.path === 'status').options.push('pending_review');
  const schemaEdit = { revision: inspection.revision, settings: { version: 1, collections: { filings: { label: 'Election filings', fields: reordered } } } };
  inspection = await saveSchema(server, state, schemaEdit, testSchemaPath, destination);
  assert.equal(inspection.collections.find(row => row.kind === 'filings').label, 'Election filings');
  assert.equal(state.editorFields.filings[0].path, reordered[0].path);
  assert.equal(state.editorFields.filings.find(field => field.path === 'status').label, 'Filing status');
  state.validateChanges('filings', { status: 'pending_review' });
  await assert.rejects(saveSchema(server, state, schemaEdit, testSchemaPath, destination), /another session/);
  const badOptions = structuredClone(schemaEdit.settings);
  badOptions.collections.filings.fields.find(field => field.path === 'status').options = ['pending_review'];
  await assert.rejects(saveSchema(server, state, { revision: inspection.revision, settings: badOptions }, testSchemaPath, destination), /in use/);
  const badPath = structuredClone(schemaEdit.settings);
  badPath.collections.filings.fields[0].path = 'changed_storage_path';
  await assert.rejects(saveSchema(server, state, { revision: inspection.revision, settings: badPath }, testSchemaPath, destination), /cannot be changed/);
  const badType = structuredClone(schemaEdit.settings);
  badType.collections.filings.fields[0].type = 'number';
  await assert.rejects(saveSchema(server, state, { revision: inspection.revision, settings: badType }, testSchemaPath, destination), /cannot be changed/);
  const badLabel = { version: 1, collections: { people: { label: '' } } };
  await assert.rejects(saveSchema(server, state, { revision: inspection.revision, settings: badLabel }, testSchemaPath, destination), /labels need/);
  const reset = await saveSchema(server, state, { revision: inspection.revision, settings: { version: 1, collections: {} } }, testSchemaPath, destination);
  assert.equal(reset.collections.find(row => row.kind === 'filings').label, 'Filings');
  assert.throws(() => state.validateChanges('filings', { status: 'pending_review' }));
  const editorial = await server.ssrLoadModule('/src/lib/editorial.ts');
  const { applyStructure, validateStructure } = await server.ssrLoadModule('/src/lib/editor-structure.ts');
  const directoryData = await server.ssrLoadModule('/src/lib/entities.ts');
  const graph = structuredClone(Object.fromEntries(['people', 'offices', 'parties', 'places', 'filings'].map(kind => [kind, directoryData[kind]])));
  const moved = graph.filings.find(row => !row.runningMateId && row.personId);
  const oldPersonId = moved.personId;
  const targetPerson = graph.people.find(row => row.id !== oldPersonId);
  const targetOffice = graph.offices.find(row => row.id !== moved.officeId);
  const targetParty = graph.parties.find(row => row.id !== moved.partyId);
  const targetPlace = graph.places.find(row => row.type === 'City');
  const renamedId = targetPerson.id;
  const structural = { version: 1, people: { [targetPerson.id]: { name: 'Edited display name' } }, offices: {}, parties: {}, places: {}, filings: { [moved.recordId]: { personId: targetPerson.id, officeId: targetOffice.id, partyId: targetParty.id, placeId: targetPlace.id } } };
  applyStructure(graph, structural);
  assert.equal(targetPerson.id, renamedId, 'Renames preserve stable routes');
  assert.equal(targetPerson.name, 'Edited display name');
  assert.equal(moved.personId, targetPerson.id);
  assert(targetPerson.filings.includes(moved));
  assert(!graph.people.find(row => row.id === oldPersonId).filings.includes(moved));
  assert(targetOffice.filings.includes(moved)); assert(targetParty.filings.includes(moved)); assert(targetPlace.filings.includes(moved));
  assert.equal(moved.officeName, targetOffice.name);
  assert.equal(moved.partyName, targetParty.name);
  assert(targetOffice.placeIds.includes(targetPlace.id));
  assert.throws(() => validateStructure(graph, { ...structural, filings: { [moved.recordId]: { officeId: 'missing-office' } } }), /Unknown/);
  assert.throws(() => validateStructure(graph, { ...structural, filings: { [moved.recordId]: { personId: targetPerson.id, runningMateId: targetPerson.id } } }), /own running mate/);
  assert.throws(() => validateStructure(graph, { ...structural, places: { [targetPlace.id]: { parentId: targetPlace.id } } }), /existing county/);
  for (const kind of ['offices', 'parties', 'places']) {
    for (const path of ['website', 'facebook', 'instagram', 'x', 'bluesky', 'youtube', 'linkedin', 'wikipedia', 'wikidata', 'links']) {
      assert(state.editorFields[kind].some(field => field.path === path), `${kind} is missing ${path}`);
    }
    const baseline = [{ url: 'https://example.org', label: 'Official website' }, { url: 'https://facebook.com/imported', source: 'https://example.org', verifiedOn: '2026-11-06' }, { url: 'https://en.wikipedia.org/wiki/Town' }];
    const result = editorial.applyEntityLinks(kind, baseline, { website: 'https://new.example.org', instagram: 'https://instagram.com/newaccount', facebook: '' });
    assert(result.some(link => link.url === 'https://new.example.org'));
    assert(result.some(link => link.url === 'https://instagram.com/newaccount'));
    assert(!result.some(link => link.url.includes('facebook.com')));
    assert(result.some(link => link.url.includes('wikipedia.org')));
    assert.deepEqual(editorial.applyEntityLinks(kind, baseline, {}), baseline);
    const rich = [{ url: 'https://example.org/one', label: 'One', detail: 'Public resource', source: 'https://example.org', verifiedOn: '2026-11-06' }, { url: 'https://example.org/two', label: 'Two' }];
    assert.deepEqual(editorial.applyEntityLinks(kind, baseline, { links: rich }), rich, 'Multiple links and source metadata survive');
  }
  const { configureFields } = await server.ssrLoadModule('/src/lib/editor-schema.ts');
  const legacyPresentation = configureFields(editorial.baseEditorFields, { version: 1, collections: { people: { fields: [{ path: 'contact.facebook', label: 'Facebook' }, { path: 'facebook', label: 'Facebook' }, { path: 'links', label: 'Links' }] } } });
  assert(!legacyPresentation.people.some(field => field.path === 'contact.facebook' || field.path === 'facebook'));
  for (const [kind, path] of [['people', 'photo.src'], ['offices', 'photo.src'], ['places', 'photo.src'], ['places', 'emblem.src'], ['parties', 'logo']]) {
    assert.equal(state.editorFields[kind].find(field => field.path === path)?.type, 'image', `${kind} exposes ${path} to the image picker`);
    editorial.validateChanges(kind, { [path]: '/images/uploads/test.png' });
    assert.throws(() => editorial.validateChanges(kind, { [path]: '//outside.example/image.png' }));
  }
  const imageLibrary = await server.ssrLoadModule('/src/lib/entity-images.ts');
  const imageOverrides = (await server.ssrLoadModule('/src/data/editor-overrides.json')).default;
  const originalOffices = imageOverrides.offices;
  try {
    const original = { src: '/images/original.webp', title: 'Original image', artist: 'Original creator', license: 'Original license', licenseUrl: '', sourceUrl: 'https://example.org/original' };
    imageOverrides.offices = { ...originalOffices, '__image_test__': { 'photo.src': '/images/uploads/replacement.png' } };
    let image = imageLibrary.entityImageFor('offices', '__image_test__', 'photo', original);
    assert.equal(image.src, '/images/uploads/replacement.png');
    assert.equal(image.artist, '', 'Replacement never inherits a different image’s credit');
    imageOverrides.offices.__image_test__['photo.artist'] = 'New creator';
    assert.equal(imageLibrary.entityImageFor('offices', '__image_test__', 'photo', original).artist, 'New creator');
    imageOverrides.offices.__image_test__['photo.src'] = '';
    assert.equal(imageLibrary.entityImageFor('offices', '__image_test__', 'photo', original), undefined);
    delete imageOverrides.offices.__image_test__;
    assert.equal(imageLibrary.entityImageFor('offices', '__image_test__', 'photo', original).artist, 'Original creator');
  } finally { imageOverrides.offices = originalOffices; }
  const canonicalFields = editorial.editorFields.people;
  assert(canonicalFields.some(field => field.path === 'links'));
  assert(!canonicalFields.some(field => field.path === 'website' || field.path === 'contact.website' || field.path === 'facebook'));
  const sourceLinks = [{ url: 'https://example.org', platform: 'website', source: 'Verified source', verifiedOn: '2026-11-06' }, { url: 'https://facebook.com/original', platform: 'facebook' }];
  const migrated = editorial.migratePersonLinks({ 'contact.facebook': 'https://facebook.com/campaign', facebook: 'https://facebook.com/manual', 'contact.website': '', biography: 'Keep me' }, sourceLinks);
  assert.equal(migrated.biography, 'Keep me');
  assert.equal(migrated.links.length, 1);
  assert.equal(migrated.links[0].url, 'https://facebook.com/manual');
  assert(!('contact.website' in migrated));
  editorial.validateChanges('people', migrated);
  const retained = editorial.migratePersonLinks({ 'contact.facebook': 'https://facebook.com/manual' }, sourceLinks);
  assert.equal(retained.links.find(link => link.platform === 'website').source, 'Verified source');
  assert.deepEqual(editorial.applyEntityLinks('people', sourceLinks, { links: [] }), [], 'A clear cannot reintroduce contact fallback links');
  const mockPerson = { id: 'example', filings: [{ personId: 'example', contact: { website: 'https://example.org', facebook: 'https://facebook.com/current' } }] };
  const importedLinks = editorial.importedPersonLinks(mockPerson, {}, sourceLinks);
  assert.equal(importedLinks.length, 3, 'Distinct accounts survive while identical URLs are deduplicated');
  assert.equal(importedLinks[0].source, 'Verified source');
  const oldSettings = { version: 1, collections: { offices: { fields: [{ path: 'contact.email', label: 'Office email' }] } } };
  const expanded = configureFields(editorial.baseEditorFields, oldSettings);
  assert.equal(expanded.offices[0].label, 'Office email');
  assert(expanded.offices.some(field => field.path === 'website'), 'Existing schema preferences do not hide new fields');
  const { importedOfficeProfile, officeProfile } = await server.ssrLoadModule('/src/lib/entity-profiles.ts');
  assert.equal(typeof importedOfficeProfile, 'function'); assert.equal(typeof officeProfile, 'function');
  assert.equal(editorial.editorProfileFor('offices', 'test', { description: 'Imported' }, { 'profile.description': 'Manual' }).description, 'Manual');
  assert.equal(editorial.editorProfileFor('places', 'test', { officialWebsite: 'https://old.example.org' }, { website: 'https://new.example.org' }).officialWebsite, 'https://new.example.org');
  const { contactAddresses, addressMapUrl, isMailingAddress } = await server.ssrLoadModule('/src/lib/contact-addresses.ts');
  const addressList = [{ label: 'Office', value: '825 N 300 W, Salt Lake City, UT' }, { label: 'Mailing', value: 'P.O. Box 522340, Salt Lake City, UT 84152' }];
  editorial.validateChanges('people', { 'contact.address': addressList });
  assert.deepEqual(contactAddresses('123 Main St'), [{ label: 'Address', value: '123 Main St' }]);
  assert.deepEqual(contactAddresses('Campaign office: 123 Main St\nMailing: PO Box 1'), [{ label: 'Campaign office', value: '123 Main St' }, { label: 'Mailing', value: 'PO Box 1' }]);
  assert.deepEqual(contactAddresses([]), []);
  assert.equal(new URL(addressMapUrl(addressList[1])).searchParams.get('query'), addressList[1].value);
  assert.notEqual(addressMapUrl(addressList[0]), addressMapUrl(addressList[1]));
  assert.equal(isMailingAddress(addressList[0]), false);
  assert.equal(isMailingAddress(addressList[1]), true);
  assert.equal(isMailingAddress({ label: 'Address', value: 'P.O. Box 123, Salt Lake City' }), true);
  assert.equal(isMailingAddress({ label: 'Mailing address', value: '123 Main St' }), true);
  assert.throws(() => editorial.validateChanges('people', { 'contact.address': [{ label: 'Office', value: '' }] }));
  proxy = await runDevServer({ port: 0, host: '127.0.0.1', mode: 'fs', dir: directory, logLevel: 'error' });
  const endpoint = `http://127.0.0.1:${proxy.address().port}/api/v1`;
  const request = async (action, params) => {
    const response = await fetch(endpoint, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action, params }) });
    assert.equal(response.status, 200, await response.clone().text());
    return response.json();
  };
  assert.equal((await request('info')).type, 'local_fs');
  const [relative, entry] = [...state.catalog].find(([, row]) => row.kind === 'people' && row.id === 'ben-mcadams');
  const record = await readJson(join(directory, relative));
  const persist = async () => request('persistEntry', {
    branch: 'editor', entry: { path: relative, slug: entry.filename.slice(0, -5), raw: JSON.stringify(record) }, assets: [],
    options: { collectionName: 'people', commitMessage: 'Local editor check', useWorkflow: false, status: 'draft' }
  });
  record.record.overrides = { biography: 'Local editor round-trip check.', 'contact.address': addressList, links: [{ url: 'https://example.org/campaign', platform: 'website' }], priorities: [], resources: [{ label: 'Platform', description: 'Published positions', url: 'https://example.org/platform' }] };
  validateRecord(record, entry, state.validateChanges);
  await persist();
  await syncRecord(relative, state, destination);
  let compiled = await readJson(destination);
  assert.deepEqual(compiled.people['ben-mcadams'], record.record.overrides);
  let profile = editorial.applyChanges(entry.source, compiled.people['ben-mcadams']);
  assert.equal(profile.biography, 'Local editor round-trip check.');
  assert.equal(profile.links[0].url, 'https://example.org/campaign');
  assert.deepEqual(profile.contact.address, addressList, 'Multiple addresses survive a Decap save');
  assert.equal(profile.contact.email, 'press@benmcadams.com', 'Editing the website preserves the standard email field');
  assert.deepEqual(profile.priorities, [], 'An explicit empty list clears imported priorities');

  // Regenerating all Decap documents uses the tracked overrides rather than replacing them.
  await prepare(server, directory, compiled);
  assert.deepEqual((await readJson(join(directory, relative))).record.overrides, compiled.people['ben-mcadams']);
  profile = editorial.applyChanges({ ...entry.source, biography: 'A newer imported biography' }, compiled.people['ben-mcadams']);
  assert.equal(profile.biography, 'Local editor round-trip check.', 'Manual changes survive source refreshes');
  delete record.record.overrides.biography;
  await persist(); await syncRecord(relative, state, destination);
  compiled = await readJson(destination);
  profile = editorial.applyChanges({ ...entry.source, biography: 'A newer imported biography' }, compiled.people['ben-mcadams']);
  assert.equal(profile.biography, 'A newer imported biography', 'Removing an override restores inheritance');
  record.record.overrides = {};
  await persist(); await syncRecord(relative, state, destination);
  assert.equal((await readJson(destination)).people['ben-mcadams'], undefined, 'Resetting all fields removes the stored override');

  const [placeRelative, placeEntry] = [...state.catalog].find(([, row]) => row.kind === 'places' && row.context.type === 'City');
  const placeRecord = await readJson(join(directory, placeRelative));
  placeRecord.record.overrides = { instagram: 'https://www.instagram.com/exampletown/', facebook: '' };
  validateRecord(placeRecord, placeEntry, state.validateChanges);
  await request('persistEntry', { branch: 'editor', entry: { path: placeRelative, slug: placeEntry.filename.slice(0, -5), raw: JSON.stringify(placeRecord) }, assets: [], options: { collectionName: 'places', commitMessage: 'Check place social save', useWorkflow: false, status: 'draft' } });
  await syncRecord(placeRelative, state, destination);
  const placeSaved = (await readJson(destination)).places[placeEntry.id];
  const originalLinks = [{ url: 'https://example.org', label: 'Official website' }, { url: 'https://facebook.com/oldtown' }, { url: 'https://instagram.com/oldtown' }, { url: 'https://en.wikipedia.org/wiki/Town' }];
  const placeResult = editorial.applyPlaceSocial(originalLinks, placeSaved);
  assert.equal(placeResult.length, 3, 'Website and Wikipedia survive social replacement and clear');
  assert(placeResult.some(link => link.url === placeSaved.instagram));
  assert(!placeResult.some(link => link.url.includes('facebook.com')));
  assert.deepEqual(editorial.applyPlaceSocial(originalLinks, {}), originalLinks, 'Inheritance restores all imported links');
  assert.throws(() => editorial.validateChanges('places', { instagram: 'javascript:alert(1)' }));
  await prepare(server, directory, await readJson(destination));
  assert.deepEqual((await readJson(join(directory, placeRelative))).record.overrides, placeSaved, 'Town social edits survive workspace regeneration');

  for (const kind of ['offices', 'parties', 'places']) {
    const [relative, entry] = [...state.catalog].find(([, row]) => row.kind === kind);
    const record = await readJson(join(directory, relative));
    const changes = { 'contact.email': 'contact@example.org', 'contact.phone': '801-555-0100', 'contact.address': addressList, website: 'https://example.org/office', youtube: 'https://youtube.com/@testoffice' };
    record.record.overrides = changes;
    validateRecord(record, entry, state.validateChanges);
    await request('persistEntry', { branch: 'editor', entry: { path: relative, slug: entry.filename.slice(0, -5), raw: JSON.stringify(record) }, assets: [], options: { collectionName: kind, commitMessage: 'Check entity contact save', useWorkflow: false, status: 'draft' } });
    await syncRecord(relative, state, destination);
    assert.deepEqual((await readJson(destination))[kind][entry.id], changes);
    const merged = editorial.entityContact(kind, { website: 'https://example.org' }, changes);
    assert.equal(merged.email, 'contact@example.org');
    assert.equal(merged.phone, '801-555-0100');
    assert.deepEqual(merged.address, addressList);
    assert.equal(merged.website, 'https://example.org');
    assert.equal(editorial.entityContact(kind, { email: 'old@example.org' }, { 'contact.email': '' }).email, '');
    assert.throws(() => editorial.validateChanges(kind, { 'contact.email': 'invalid email' }));
    const linked = editorial.applyEntityLinks(kind, originalLinks, changes);
    assert(linked.some(link => link.url === changes.website));
    assert(linked.some(link => link.url === changes.youtube));
    assert(!linked.some(link => link.url === changes['contact.email']), 'Contact fields never become social URLs');
    await prepare(server, directory, await readJson(destination));
    assert.deepEqual((await readJson(join(directory, relative))).record.overrides, changes);
  }

  const [filingRelative, filingEntry] = [...state.catalog].find(([, row]) => row.kind === 'filings' && row.source.county && row.source.city);
  const filing = await readJson(join(directory, filingRelative));
  filing.record.overrides = { city: 'New City', county: 'Salt Lake', 'contact.email': '' };
  await atomicJson(join(directory, filingRelative), filing);
  await syncRecord(filingRelative, state, destination);
  const corrected = editorial.applyFilingChanges(filingEntry.source, (await readJson(destination)).filings[filingEntry.id]);
  assert.deepEqual(corrected.placeIds, ['salt-lake', 'salt-lake/new-city']);
  assert.equal(corrected.contact.email, '');
  assert.equal(corrected.personId, filingEntry.source.personId, 'Filing identity is preserved');
  assert.throws(() => state.validateChanges('people', { 'contact.website': 'javascript:alert(1)' }));
  assert.throws(() => state.validateChanges('people', { lastVerified: '2026-02-30' }));
  assert.throws(() => state.validateChanges('filings', { personId: 'different-person' }));
  assert.throws(() => state.validateChanges('filings', { status: 'made-up-status' }));
  assert.throws(() => validateRecord({ ...record, id: 'different-id' }, entry, state.validateChanges));
  assert.equal(await readFile(overridesPath, 'utf8'), baseline, 'Checks never change repository overrides');
  console.log(`Editor checks passed: ${state.counts.people} people, ${state.counts.filings} filings; Decap save, persistence, regeneration, inheritance, clearing, geography, and validation.`);
} finally {
  if (proxy) await new Promise(resolve => proxy.close(resolve));
  await server.close();
  await rm(directory, { recursive: true, force: true });
}
